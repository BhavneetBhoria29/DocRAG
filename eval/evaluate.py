# ── Pipeline execution ────────────────────────────────────────────────────────

def generate_pipeline_outputs(rag: "AgenticRAG", golden: list[dict]) -> list[dict]:
    """Run the real retriever + graph for each golden question."""
    retriever = rag.vector_store.get_retriever()
    rows = []
    for i, item in enumerate(golden, 1):
        q = item["question"]
        print(f"  [{i}/{len(golden)}] {q[:70]}")
        docs = retriever.invoke(q)
        contexts = [d.page_content for d in docs]
        answer = rag.graph_builder.run(q)["answer"]
        rows.append({
            "question": q,
            "answer": answer,
            "contexts": contexts,
            "ground_truth": item["ground_truth"],
        })
    return rows


def build_dataset(rows: list[dict]) -> Dataset:
    return Dataset.from_dict({
        "question":     [r["question"]     for r in rows],
        "answer":       [r["answer"]       for r in rows],
        "contexts":     [r["contexts"]     for r in rows],
        "ground_truth": [r["ground_truth"] for r in rows],
    })


# ── Statistics ────────────────────────────────────────────────────────────────

def bootstrap_ci(values, n_boot: int = 1000, alpha: float = 0.05, seed: int = 42) -> dict:
    """Mean + percentile bootstrap CI over per-sample scores (NaN-safe)."""
    vals = np.array(
        [v for v in values if v is not None and not (isinstance(v, float) and np.isnan(v))],
        dtype=float,
    )
    if vals.size == 0:
        return {"n": 0, "mean": None, "ci_low": None, "ci_high": None, "std": None}
    rng = np.random.default_rng(seed)
    boot_means = np.array([
        rng.choice(vals, size=vals.size, replace=True).mean() for _ in range(n_boot)
    ])
    lo, hi = np.percentile(boot_means, [100 * alpha / 2, 100 * (1 - alpha / 2)])
    return {
        "n": int(vals.size),
        "mean": round(float(vals.mean()), 4),
        "ci_low": round(float(lo), 4),
        "ci_high": round(float(hi), 4),
        "std": round(float(vals.std(ddof=1)), 4) if vals.size > 1 else 0.0,
    }


# ── Orchestration ─────────────────────────────────────────────────────────────

def run(golden: list[dict]):
    print("🚀 Building pipeline and generating live outputs (retrieve + answer)...\n")
    rag = AgenticRAG()  # builds corpus + vectorstore + graph from Config.DEFAULT_URLS
    rows = generate_pipeline_outputs(rag, golden)

    print("\n🧪 Scoring with RAGAS...\n")
    dataset = build_dataset(rows)
    judge = LangchainLLMWrapper(ChatOpenAI(model=JUDGE_MODEL, temperature=0))
    emb = LangchainEmbeddingsWrapper(OpenAIEmbeddings(model=EMBED_MODEL))

    results = evaluate(
        dataset=dataset,
        metrics=[
            Faithfulness(llm=judge),
            AnswerRelevancy(llm=judge, embeddings=emb),
            ContextPrecision(llm=judge),
            ContextRecall(llm=judge)
        ],
             run_config=RunConfig(max_workers=1, timeout=180, max_retries=5),
    )


    df = results.to_pandas()
    metric_cols = ["faithfulness", "answer_relevancy", "context_precision", "context_recall"]
    stats = {m: bootstrap_ci(df[m].tolist()) for m in metric_cols if m in df.columns}
    return stats, df


def save(stats: dict, df) -> Path:
    out_dir = Path(__file__).resolve().parent / "results"
    out_dir.mkdir(parents=True, exist_ok=True)
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")

    n = next((s["n"] for s in stats.values() if s["n"]), 0)
    payload = {
        "timestamp": ts,
        "judge_model": JUDGE_MODEL,
        "embedding_model": EMBED_MODEL,
        "num_samples": n,
        "metrics": stats,
    }
    json_path = out_dir / f"ragas_{ts}.json"
    json_path.write_text(json.dumps(payload, indent=2))
    df.to_csv(out_dir / f"per_sample_{ts}.csv", index=False)
    return json_path


def print_report(stats: dict) -> None:
    print("=" * 66)
    print("            RAGAS Evaluation — DocRAG live pipeline")
    print("=" * 66)
    print(f"  {'Metric':<20}{'mean':>8}{'95% CI':>22}{'n':>6}")
    print("-" * 66)
    for m, s in stats.items():
        if s["mean"] is None:
            print(f"  {m:<20}{'n/a':>8}")
            continue
        ci = f"[{s['ci_low']:.2f}, {s['ci_high']:.2f}]"
        print(f"  {m:<20}{s['mean']:>8.2f}{ci:>22}{s['n']:>6}")
    print("=" * 66)
    means = [s["mean"] for s in stats.values() if s["mean"] is not None]
    if means:
        print(f"  {'average':<20}{sum(means) / len(means):>8.2f}")
        print("=" * 66)


